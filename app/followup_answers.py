STATUS_CHECK_FOLLOWUP = "他の売場・設備の稼働状態を確認する"
CASE_SEARCH_FOLLOWUP = "事例データベースを検索する"
CLOSE_FOLLOWUP = "対応を完了する"


def build_close_answer() -> FollowupAnswer:
    """復旧報告のあとに「対応を完了する」が選ばれた場合の締めの回答."""
    return (
        "対応を完了しました。本日の対応内容はシステムカルテに記録済みです。\n"
        "また何かあれば、いつでもお声がけください。",
        "【対応クローズ】\n・ステータス: CLOSED\n・カルテ: 対応履歴を記録済み",
        ["別の件で相談する"],
    )


def _build_status_answer(domain: str) -> FollowupAnswer:
    lines = [f"・{label}: 正常" for label in _DOMAIN_LABELS.values()]
    handled = _DOMAIN_LABELS.get(domain, domain)
    return (
        "【稼働状況】\n"
        "店舗の主な設備の稼働状態は次のとおりです。\n"
        + "\n".join(lines)
        + f"\n※先ほど対応した{handled}も正常に戻っています。\n\n"
        "【理由】\n"
        "今回のトラブルが他の設備に影響していないかを確認し、安心して営業を続けていただくためです。",
        "【設備稼働サマリー】\n"
        "・データ: デモ環境の監視スナップショット\n"
        f"・直前の対応領域: {domain.upper()}（RESOLVED）\n"
        "・未解決アラート: 0件",
        [CASE_SEARCH_FOLLOWUP, CLOSE_FOLLOWUP],
    )


def _build_case_search_answer(tickets: list[dict[str, Any]]) -> FollowupAnswer:
    rows = [t for t in tickets if t.get("ticket_id")][:3]
    if not rows:
        return (
            "【検索結果】\n今回の対応に類似する過去事例は見つかりませんでした。\n\n"
            "【ポイント】\n今回の対応内容は新しい事例としてシステムカルテに記録済みです。",
            "【事例検索】\n・ヒット件数: 0件",
            [STATUS_CHECK_FOLLOWUP, CLOSE_FOLLOWUP],
        )
    items = [
        f"{i}. {t['ticket_id']} {t.get('title', '')}\n"
        f"   原因: {t.get('root_cause', '不明')}\n"
        f"   対処: {t.get('resolution', '記録なし')}"
        for i, t in enumerate(rows, start=1)
    ]
    return (
        "【検索結果】\n今回と似た過去の事例は次のとおりです。\n"
        + "\n".join(items)
        + "\n\n【ポイント】\n今回の対応内容も、同じ原因の再発に備えてシステムカルテに記録済みです。",
        "【事例検索】\n"
        f"・ヒット件数: {len(rows)}件\n"
        "・検索元: 過去インシデントチケット（ベクトル検索結果）",
        [STATUS_CHECK_FOLLOWUP, CLOSE_FOLLOWUP],
    )


def get_specific_followup_answer(
    candidate: str | None,
    domain: str,
    tickets: list[dict[str, Any]] | None = None,
) -> FollowupAnswer | None:
    """照合済みの候補に専用回答があれば (answer, technical_details, suggested_followups) を返す."""
    if not candidate:
        return None
    if candidate in SPECIFIC_FOLLOWUP_ANSWERS:
        answer, technical, followups = SPECIFIC_FOLLOWUP_ANSWERS[candidate]
        return answer, technical, list(followups)
    if candidate == STATUS_CHECK_FOLLOWUP:
        return _build_status_answer(domain)
    if candidate == CASE_SEARCH_FOLLOWUP:
        return _build_case_search_answer(tickets or [])
    return None
